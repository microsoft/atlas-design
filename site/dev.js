// Dev server for the Atlas documentation site. Dependency-free so we don't pull
// in concurrently/npm-run-all. It orchestrates three concerns side by side:
//
//   1. the scaffold asset watcher (sass + esbuild) — `build-assets.js --watch`
//   2. Eleventy in --serve mode
//   3. a markdown lifecycle watcher that keeps the TOC and dist output in sync
//      when .md files are ADDED or REMOVED
//
// Eleventy's own --serve watcher only reacts to edits of files that existed at
// startup: it does not re-glob for newly-added templates, nor clean output for
// removed ones, and toc.js runs only once (before this script). The lifecycle
// watcher below closes that gap by regenerating the TOC, pruning stale output,
// and restarting Eleventy so it rediscovers the template set.
//
// The initial TOC is generated by the wireit `toc` dependency of `start`, so
// this file assumes src/scaffold/toc.json already exists on boot.
import { spawn } from 'child_process';
import { watch, existsSync, rmSync, readdirSync } from 'fs';
import path from 'path';
import process from 'process';
import { createRequire } from 'module';

const require = createRequire(import.meta.url);
const node = process.execPath;
const cwd = process.cwd();
const srcDir = path.join(cwd, 'src');
const distDir = path.join(cwd, 'dist');
const scaffoldDir = path.join(srcDir, 'scaffold');

// Resolve Eleventy's CLI entry so we can run it as a single `node` process.
// Spawning the binary directly (rather than through the npx.cmd shell) means a
// single kill() reliably frees port 1111 when we restart it — critical on
// Windows, where killing the shell wrapper can leave the server holding the port.
const eleventyCli = path.join(path.dirname(require.resolve('@11ty/eleventy')), '..', 'cmd.cjs');

let shuttingDown = false;

// --- long-running asset watcher --------------------------------------------

const assets = spawn(node, ['build-assets.js', '--watch'], { stdio: 'inherit', cwd });
assets.on('exit', code => {
	if (!shuttingDown) {
		console.error(`[dev] asset watcher exited (${code}); shutting down.`);
		shutdown(code ?? 0);
	}
});

// --- restartable Eleventy server -------------------------------------------

let eleventy = null;
let restartingEleventy = false;

function startEleventy() {
	const child = spawn(node, [eleventyCli, '--serve'], { stdio: 'inherit', cwd });
	child.on('exit', code => {
		if (restartingEleventy || shuttingDown) return;
		console.error(`[dev] eleventy exited (${code}); shutting down.`);
		shutdown(code ?? 0);
	});
	eleventy = child;
}

function restartEleventy() {
	if (!eleventy || shuttingDown) return;
	restartingEleventy = true;
	const previous = eleventy;
	// Wait for the old process to fully exit before spawning a new one, otherwise
	// the fresh server races the old one for port 1111 (EADDRINUSE).
	previous.once('exit', () => {
		restartingEleventy = false;
		if (!shuttingDown) startEleventy();
	});
	previous.kill();
}

startEleventy();

// --- markdown lifecycle watcher --------------------------------------------

function listMarkdown() {
	const found = new Set();
	const walk = dir => {
		for (const entry of readdirSync(dir, { withFileTypes: true })) {
			const full = path.join(dir, entry.name);
			if (entry.isDirectory()) {
				// Scaffold holds templates and generated data, not doc pages.
				if (full === scaffoldDir) continue;
				walk(full);
			} else if (entry.isFile() && entry.name.endsWith('.md')) {
				found.add(full);
			}
		}
	};
	walk(srcDir);
	return found;
}

let known = listMarkdown();

function regenerateToc() {
	return new Promise(resolve => {
		spawn(node, ['toc.js'], { stdio: 'inherit', cwd }).on('exit', () => resolve());
	});
}

function distHtmlFor(mdAbsPath) {
	const rel = path.relative(srcDir, mdAbsPath).replace(/\.md$/, '.html');
	return path.join(distDir, rel);
}

let debounce = null;
function scheduleReconcile() {
	clearTimeout(debounce);
	debounce = setTimeout(reconcile, 150);
}

let reconciling = false;
async function reconcile() {
	if (reconciling) {
		scheduleReconcile();
		return;
	}
	reconciling = true;
	try {
		const current = listMarkdown();
		const added = [...current].filter(f => !known.has(f));
		const removed = [...known].filter(f => !current.has(f));
		if (added.length === 0 && removed.length === 0) return;
		known = current;

		for (const md of removed) {
			const out = distHtmlFor(md);
			if (existsSync(out)) {
				rmSync(out);
				console.log(`[dev] pruned stale output ${path.relative(cwd, out)}`);
			}
		}

		// Regenerate the TOC (updates nav on every page via the toc.json watch
		// target) and restart Eleventy so it re-globs templates.
		await regenerateToc();
		console.log(
			`[dev] markdown changed (+${added.length} / -${removed.length}); restarting eleventy.`
		);
		restartEleventy();
	} finally {
		reconciling = false;
	}
}

try {
	watch(srcDir, { recursive: true }, (_event, filename) => {
		if (!filename) {
			scheduleReconcile();
			return;
		}
		const segments = filename.split(path.sep);
		if (filename.endsWith('.md') && !segments.includes('scaffold')) {
			scheduleReconcile();
		}
	});
} catch {
	console.warn('[dev] recursive fs.watch unavailable; md add/remove sync disabled.');
}

// --- shutdown ---------------------------------------------------------------

function shutdown(code) {
	if (shuttingDown) return;
	shuttingDown = true;
	for (const child of [assets, eleventy]) {
		if (child && !child.killed) {
			try {
				child.kill();
			} catch {
				/* already gone */
			}
		}
	}
	process.exit(code);
}

process.on('SIGINT', () => shutdown(0));
process.on('SIGTERM', () => shutdown(0));
